# ============================================================================
# led.s —— FPGA 上板演示程序（MMIO → LED）
# ----------------------------------------------------------------------------
# 功能：写 0xF0000000 到 MMIO 端口，低 8 位输出到板载 LED，
#       1→2→4→...→128 依次点亮（跑马灯），带软件延时。
# 上板现象：按下复位后 LED 依次左移循环闪烁。
# ============================================================================
start:
    li   t0, 0xF0000000      # MMIO 端口地址（FPGA 顶层据此点亮 LED）
    li   t1, 1               # 初始点亮 LED0
loop:
    sw   t1, 0(t0)           # 写 LED（io_write 1 拍）
    slli t2, t1, 1           # 左移一位
    li   t3, 0x100
    bne  t2, t3, keep        # 到 0x100 则回 1
    li   t1, 1
    j    delay
keep:
    mv   t1, t2
delay:
    li   t4, 0x20000         # 软件延时计数
d1:
    addi t4, t4, -1
    bnez t4, d1
    j    loop
