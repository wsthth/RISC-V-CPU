# ============================================================================
# led.s —— FPGA 上板演示程序（MMIO → LED，1Hz 方波闪烁）
# ----------------------------------------------------------------------------
# 功能：写 0xF0000000 到 MMIO 端口。
#       亮 1 秒（写 0x01）→ 灭 1 秒（写 0x00）循环，肉眼明显可见。
# 延时：50MHz 时钟，1 周期 20ns；25000000 次迭代 × 2 条指令 ≈ 1.0s。
# ============================================================================
start:
    li   t0, 0xF0000000      # MMIO 端口地址（FPGA 顶层据此点亮 LED）
loop:
    li   t1, 1
    sw   t1, 0(t0)           # LED 亮（低电平点亮 → 引脚输出 0）
    li   t4, 25000000        # 延时计数 ≈ 1.0s
d1:
    addi t4, t4, -1
    bnez t4, d1
    li   t1, 0
    sw   t1, 0(t0)           # LED 灭
    li   t4, 25000000        # 延时计数 ≈ 1.0s
d2:
    addi t4, t4, -1
    bnez t4, d2
    j    loop
