# =============================================================================
# hazard.s - 数据冒险测试（旁路转发 + Load-Use 停顿）
# 结果写入 DMEM[0x100..0x114]，TB 对照检查
# 期望值：
#   0x100=240  0x104=241  0x108=481  0x10C=240
#   0x110=224  0x114=722
# =============================================================================
start:
    li   t0, 0x100
    li   t1, 10
    li   t2, 20
    # ---- RAW 连续依赖（转发链）----
    add  t3, t1, t2        # 30
    add  t3, t3, t3        # 60
    add  t3, t3, t3        # 120
    add  t3, t3, t3        # 240
    sw   t3, 0(t0)         # 240
    # ---- Load-Use（停顿）----
    lw   t4, 0(t0)         # 240
    addi t4, t4, 1         # 241（依赖上一 load）
    sw   t4, 4(t0)         # 241
    # ---- 多级 RAW 混合 ----
    add  t5, t4, t3        # 481
    sub  t6, t5, t4        # 240
    and  s3, t5, t3        # 481 & 240 = 224
    sw   t5, 8(t0)
    sw   t6, 12(t0)
    sw   s3, 16(t0)
    # ---- 双 load 依赖 ----
    lw   s0, 4(t0)         # 241
    lw   s1, 8(t0)         # 481
    add  s2, s0, s1        # 722
    sw   s2, 20(t0)
done:
    beq  x0, x0, done
